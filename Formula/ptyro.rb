# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.44/ptyro-0.0.44-aarch64-apple-darwin.tar.gz"
      sha256 "746411759d87c583dfc056dc69b89678b406d3bdc2d31f4380e8de34a298f559"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.44/ptyro-0.0.44-x86_64-apple-darwin.tar.gz"
      sha256 "81821170fe90e7ca70fe214f9f136615e32d40359eb903b35b7941279b617ab4"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.44/ptyro-0.0.44-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "125e6d406d4f475e8849d397f0dc4c7a32fb46e2509cef7cce0faa3f72738e36"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.44/ptyro-0.0.44-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "5688c224c3178a97da7bd7d31f081298ddae63f0b04883d24e444abe7416d921"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
