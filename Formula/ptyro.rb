# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.99/ptyro-0.0.99-aarch64-apple-darwin.tar.gz"
      sha256 "b147015bb9bda1de5aef949fde4303bdc49c5ac80e198f2bd089f4d6542ff081"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.99/ptyro-0.0.99-x86_64-apple-darwin.tar.gz"
      sha256 "24ff11ac6ac43a9794db52ac0d7aa04412e77bbcc57c03082549497e8feb0098"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.99/ptyro-0.0.99-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "6e0c91aabb3d641186fdb1f87bee09fa87921171fb4a64f6e5ff49595a647004"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.99/ptyro-0.0.99-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "83f453c674fb209dd08f537deb9c8bd8622bbb715b0b19acae27667883f2b76e"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
