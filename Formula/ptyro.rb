# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.22/ptyro-0.0.22-aarch64-apple-darwin.tar.gz"
      sha256 "20f9e76cb490be9d1237f79b4855afd184fc40869cd5638734d402853830ad90"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.22/ptyro-0.0.22-x86_64-apple-darwin.tar.gz"
      sha256 "b11a3cc294174c65d1f2965de0c4ad597b99a4644477460395e4284fbae38eef"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.22/ptyro-0.0.22-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "77796dd824a7fc353a61d9dead7b2fc0da49c3177c63f801d6ca1b7e4946862b"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.22/ptyro-0.0.22-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "12117adb362134feb181056ac158e0f72c068362d09217a4c8a7b52f5e964f29"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
