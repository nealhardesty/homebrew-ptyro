# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.101/ptyro-0.0.101-aarch64-apple-darwin.tar.gz"
      sha256 "903cbb35f5bcc32aa410d8cd7afa06f38ae44b563ee8641e4ec287cc83440abb"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.101/ptyro-0.0.101-x86_64-apple-darwin.tar.gz"
      sha256 "72eb412b03818b6d22ad53c42062b4926934e5b20a5ddc86b6da299a51621682"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.101/ptyro-0.0.101-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "daea3fac5867ce91276d2050d639f382cb434e9156aa7caf6a1b7d70acb3c02b"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.101/ptyro-0.0.101-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "5922b670349e6f21cbcdf86d37f7fdb91f0abccfb99b7d7f8c794b8443a40d25"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
