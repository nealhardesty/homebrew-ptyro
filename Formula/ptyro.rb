# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.97/ptyro-0.0.97-aarch64-apple-darwin.tar.gz"
      sha256 "2101120700a99acf4238cf191948e6eac5b5d3f8fdc77c5bf3093a157dcbe8a3"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.97/ptyro-0.0.97-x86_64-apple-darwin.tar.gz"
      sha256 "d2c73b04fd601d2e86caa2a1ad37717bc947a4251a573a384176a4908bd24413"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.97/ptyro-0.0.97-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "25206493595d814753c89e9b12e9c1c13c27167dfc41ca95b2114f05d10e2e0f"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.97/ptyro-0.0.97-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "3242a3011f80dc633ef02868b18ee750727214094e66086006a3ef3d098595f3"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
