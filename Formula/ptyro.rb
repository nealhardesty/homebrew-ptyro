# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.86/ptyro-0.0.86-aarch64-apple-darwin.tar.gz"
      sha256 "e3102f0e193422199f739abeffebc52d5b24c59bc1a684554a13a9a5b478a083"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.86/ptyro-0.0.86-x86_64-apple-darwin.tar.gz"
      sha256 "7ff579c780f6fbab01980e2fb104e86a4efb212879f6e4cf82ee31ed0a6c124c"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.86/ptyro-0.0.86-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "1b643d5fa1cb5fed0becc826c296a162a4229274ba25cb8cd168725f05c08e84"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.86/ptyro-0.0.86-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "a71c7ce3d58fc1a9386c10fc19265a5ee702d4bdcc09742f00e35bc6398c8c36"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
