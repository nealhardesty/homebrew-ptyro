# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.60/ptyro-0.0.60-aarch64-apple-darwin.tar.gz"
      sha256 "50c73a24184954820b6b4d3c16d2ca986e9cc259145d8d3ff423a8436c513fe0"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.60/ptyro-0.0.60-x86_64-apple-darwin.tar.gz"
      sha256 "4c9ebafe00c6df13c3eeba0f196430cf42f222c84e7e2d306673d61283c284a8"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.60/ptyro-0.0.60-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "6cded7d175468d0dde0aca1fc391d38108604baaf801bbb747ea1b3dbd5e304b"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.60/ptyro-0.0.60-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "4aee8bacead4694f692afd6b02dc14b1383e6f221a6035b0b31f5fd7246cfbfe"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
