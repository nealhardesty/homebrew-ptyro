# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.24/ptyro-0.0.24-aarch64-apple-darwin.tar.gz"
      sha256 "49d4e4561492959b1a33b7403921ec20c9b4359f3e354308f7ae3b93d1a3dd1d"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.24/ptyro-0.0.24-x86_64-apple-darwin.tar.gz"
      sha256 "d7d2bad0fba93029e00e43ece0a4013af64396c122feee15f959e0519a6f8140"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.24/ptyro-0.0.24-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "8bd04d30ed874c2ab610d788bf7dab24b11e0bedbb9b021e5d578bb657ca05eb"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.24/ptyro-0.0.24-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "dfed5f839a45b0347f25ec3d1f89b68c91027ca1d205c7e8f639a762ee0d07c6"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
