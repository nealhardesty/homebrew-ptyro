# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.41/ptyro-0.0.41-aarch64-apple-darwin.tar.gz"
      sha256 "39b0cd183df7662428f4f0be169c955fa497b625dc35c0095246ac70970dc3ae"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.41/ptyro-0.0.41-x86_64-apple-darwin.tar.gz"
      sha256 "d270b7b8dd23a82fdfdb8b487d039c76b1aeae58e1ca5cf4d0b25c1e653f5a98"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.41/ptyro-0.0.41-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "f6ff72593a6999954ca7db27730bb5d7cc7fee382dcf8d659e010f58bf9aa7de"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.41/ptyro-0.0.41-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "6461b0a190ec92e7316e338d9b54a8887704c1419af4a66d43d6f5b23197f85b"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
