# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.84/ptyro-0.0.84-aarch64-apple-darwin.tar.gz"
      sha256 "d1832d1f242f4b1f6c25b3fc7bfd790234701dad06d622707ebca7f43b7c375f"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.84/ptyro-0.0.84-x86_64-apple-darwin.tar.gz"
      sha256 "1bcc7c7593f4c80ea5a5ec1bc9d750ddbefed1038d8a89479b3dc657c2f3badf"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.84/ptyro-0.0.84-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "6e0487d6de9a6de8c877ef2e719b80bd05af1573eb71535b73cf80479593e133"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.84/ptyro-0.0.84-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "e890eb702d3c76f7aaddf89ce029d35570732aed28e53eaf557aa9d297a6a4fd"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
