# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.42/ptyro-0.0.42-aarch64-apple-darwin.tar.gz"
      sha256 "30ab526c70cf2b3fbf42acd9a09b8db731335d34ec41a20a252d7753b8c0d747"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.42/ptyro-0.0.42-x86_64-apple-darwin.tar.gz"
      sha256 "a3dc751c1f7b6c5f9692b6bc55ff6aa2826e255d9d79d0bac0720ec59e9155d3"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.42/ptyro-0.0.42-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "5fe6a126eaf1ec748458cdbaed273dcebe6bd7aeed52d884c679f9d2c8ec2ae2"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.42/ptyro-0.0.42-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "e0532d5be8590dba34b7e371cbe18a9d5cf2075b7b4212bf6711ea5d785079f3"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
