# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.25/ptyro-0.0.25-aarch64-apple-darwin.tar.gz"
      sha256 "f12641863a1b4ce46179192cd93719a84554ffa5f064ffd12a3a2d75ad2d56f9"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.25/ptyro-0.0.25-x86_64-apple-darwin.tar.gz"
      sha256 "476737bfbc6941c21159a292a4b3d8e5e23ee53f8e057a61bb05c738c5f61023"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.25/ptyro-0.0.25-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "752099914ab82df583096c27b0772bea62049d46b1c89ed380cea76e2a8ba7f6"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.25/ptyro-0.0.25-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "f11ee11f3335c6cfefca29a6f17f10dcc331209a75002e2ca6f8e8e151505647"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
