# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.11/ptyro-0.0.11-aarch64-apple-darwin.tar.gz"
      sha256 "445e7e8ae1e4235cf10e27dc267db0cd095a8d8ce662e3ba0e2d1da29460741f"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.11/ptyro-0.0.11-x86_64-apple-darwin.tar.gz"
      sha256 "2f4559c561b8b850c823913a55aa40175d7c9c0596f8ebf0ee67ff7034c7d143"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.11/ptyro-0.0.11-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "8515b9c35dafb1424048efc1c6dd441db2f9f8d1c8bbcc18c63072af830f82ed"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.11/ptyro-0.0.11-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "cda555bebef03609557043c9d8f0c19e91d22a5d977be158ac05a3107b08e82d"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
