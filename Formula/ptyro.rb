# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.29/ptyro-0.0.29-aarch64-apple-darwin.tar.gz"
      sha256 "e4ed44c9da71873d185ecb9ae608ea8175b8c7fa31972f2f715747372741db46"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.29/ptyro-0.0.29-x86_64-apple-darwin.tar.gz"
      sha256 "264b91a7cf0c68ff4f3848389c2e338116dd18ebcdf827615aa53b7d23a73c45"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.29/ptyro-0.0.29-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "b41324309c03eab639b4a36619a82e3f7933af154468a3ca88a274b0286a4a7a"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.29/ptyro-0.0.29-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "643fa5769d99f38f709af6f81c6a11405e63ac9e1c7aeb0caf1f9006920978a5"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
