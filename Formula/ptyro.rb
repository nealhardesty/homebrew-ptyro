# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.70/ptyro-0.0.70-aarch64-apple-darwin.tar.gz"
      sha256 "2b63487e5a83d5b48d2d14d9e6dd75905382938e31ca5657d0ea59fb7991853a"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.70/ptyro-0.0.70-x86_64-apple-darwin.tar.gz"
      sha256 "dcb518ebc61ae3eb3beed636084b7cdb3d4078ea90ed75a8477a2c064aa78452"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.70/ptyro-0.0.70-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "c541b6bf591e929b8de946e88ab07b3404d72ff006c42865dc5e4ec4c04e8608"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.70/ptyro-0.0.70-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "bc1e236c80933bce88bda5c1971918191d107133dd91d27d4acecaf519d6a4ef"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
