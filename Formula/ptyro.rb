# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.63/ptyro-0.0.63-aarch64-apple-darwin.tar.gz"
      sha256 "362fb6accfa2313e3689d3220902bb0932b469a0d22d949696640c326b4d322b"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.63/ptyro-0.0.63-x86_64-apple-darwin.tar.gz"
      sha256 "2e17f82a80b9d2d1a0bdee2cfddac6487e8e17a41faed426c6670470283ee300"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.63/ptyro-0.0.63-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "05193c9c51cf8e2977454f458bd9b740de2ca7ff1e4c21fea2ec87c97decd530"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.63/ptyro-0.0.63-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "d75eec75cc4456c3fc55f1a2f842252280b5d6524fed85c97ffe829a38ce971b"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
