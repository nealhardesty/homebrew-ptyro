# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.59/ptyro-0.0.59-aarch64-apple-darwin.tar.gz"
      sha256 "dbb6f67a165bc4874c9dafc67cad90cab7f01864a1161ecece2214b0a76ecb4f"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.59/ptyro-0.0.59-x86_64-apple-darwin.tar.gz"
      sha256 "5fd7af6cb979933c19b7f940937a068ac507423a089a0248dc51acd41c410dce"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.59/ptyro-0.0.59-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "bd926b6e508ac359820213c226567b32252610f7819a0cedc2e082885bd2ce88"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.59/ptyro-0.0.59-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "9d57e3433ab26b533eb84b142dd9018872b084410c429e960e8e72144467c2b9"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
