# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.9/ptyro-0.0.9-aarch64-apple-darwin.tar.gz"
      sha256 "60176a159d455b1127aff3de7003dcb6097a96c4e10c46073d91050cad7e616c"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.9/ptyro-0.0.9-x86_64-apple-darwin.tar.gz"
      sha256 "dad899abd422c096a26e1a696b6688b51dc8857771b06297e2bd0a85eb8cbdb3"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.9/ptyro-0.0.9-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "b9dd993b067b1fc6b3fa919d7a7c68c398a81a705300d728d440f76e65bb896d"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.9/ptyro-0.0.9-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "3878a3b1d20475e397414c3c3ffa63344b32ce96b9e2465d2a9df3463d63ed04"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
