# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.95/ptyro-0.0.95-aarch64-apple-darwin.tar.gz"
      sha256 "f4b8b2503c7efefea41518a9dd1e50d49d581f94198cb64f2e588656ce589456"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.95/ptyro-0.0.95-x86_64-apple-darwin.tar.gz"
      sha256 "4d055aa82b0b3f0cd556cdc2601764285665b0f69c634a76a2a5cd0de58d3661"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.95/ptyro-0.0.95-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "059e343864c43ad60c3dd486aa3442956589faf3e040eee48b3ad5b6643deeb1"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.95/ptyro-0.0.95-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "4edaff716868ecb0c0ec0d0daaec726c24ada0a02085b8f7e64de8ab43b4686a"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
