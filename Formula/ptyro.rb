# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.10/ptyro-0.0.10-aarch64-apple-darwin.tar.gz"
      sha256 "19b8090e06503fddb7bfe8f6937a098f676f1d2b1891d0c6ad52b4cadde646cd"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.10/ptyro-0.0.10-x86_64-apple-darwin.tar.gz"
      sha256 "3f3a64fde81ee2c3b1d0bfd6e774d860fb0b6241d1d3f88ce379e8fb6132db75"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.10/ptyro-0.0.10-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "70c364516cbe821935a0b778f902b1cdd18529d00da25f99ca7313b1c05d103c"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.10/ptyro-0.0.10-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "8d604a0daf7a1705da18f3ce492144791270a8edbdf51a96cdddfecf6e5165ab"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
