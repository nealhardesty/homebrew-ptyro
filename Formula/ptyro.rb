# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.28/ptyro-0.0.28-aarch64-apple-darwin.tar.gz"
      sha256 "75d69b6263b7797f342c08f737c450220e81643f0bcd9bf59731267fed2633d6"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.28/ptyro-0.0.28-x86_64-apple-darwin.tar.gz"
      sha256 "bae2d2f9f282c72359b970b6196b3bdb16736526d8442b8912780fa9c598da07"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.28/ptyro-0.0.28-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "7dccaafc24d402ef6f8d3e0667ad67a2eded8df386e66d96880fddf5701e490f"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.28/ptyro-0.0.28-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "158e520a7770857de9ee48806e88047cdee84ec7cf0dd77a86731188a27dc624"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
