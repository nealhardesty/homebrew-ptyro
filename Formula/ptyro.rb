# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.94/ptyro-0.0.94-aarch64-apple-darwin.tar.gz"
      sha256 "cd166bc623406c15cc61e3c86adcc6df9b7135b1f7eaec8d005dfa6a13705d9f"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.94/ptyro-0.0.94-x86_64-apple-darwin.tar.gz"
      sha256 "6aa7fa4e4aefba3aa071ae3bffcfe8867ce47a136434d70ef90dcaf664aa5257"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.94/ptyro-0.0.94-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "33c7a089d178e09b6657aa17eaa4f0c8de182d5855586f92ae0d5cc1d67635ff"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.94/ptyro-0.0.94-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "5a3c97db5fc7f5f09c1b1db819414064d60502a868a6abbaff7fd3ec9bb52af9"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
