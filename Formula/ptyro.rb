# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.55/ptyro-0.0.55-aarch64-apple-darwin.tar.gz"
      sha256 "baab69b961f9f126c2b6d44a19d96c55dd33260b6d59f5856fa1ce939b7c78eb"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.55/ptyro-0.0.55-x86_64-apple-darwin.tar.gz"
      sha256 "dd703c6a37f99e72f3385eb15d0b04ad48b09eb6ea92fdbc6d9091aa5027cc21"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.55/ptyro-0.0.55-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "af0776be9e02a54502f2f63bec6a4632f917c5f6e1aa82ad80f82522052373d7"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.55/ptyro-0.0.55-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "5b6691638f83ef7baa144afbf467f4c693a8f0982ad0a46445a616df8802d2db"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
