# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.100/ptyro-0.0.100-aarch64-apple-darwin.tar.gz"
      sha256 "9ea383e799c8eb7b199d58adc68628165a3297da1cff0c40eac7e138d3d1b288"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.100/ptyro-0.0.100-x86_64-apple-darwin.tar.gz"
      sha256 "b2bfbbd0c72a9e0933da9a8b924b0cf100e611913a7b3a4e4cda5f1df3939ce4"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.100/ptyro-0.0.100-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "f630bb40fb55f3c47349271b9a34cfeb0bc88f78399dace3fffc8188f1d56dc4"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.100/ptyro-0.0.100-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "8edcb88ee8176c9e37fd79d013de0368be531a74b4da2d95ab5b3021b3c90507"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
