# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.87/ptyro-0.0.87-aarch64-apple-darwin.tar.gz"
      sha256 "85d3bdbbfd13aab8d4ef722044ad2b6ea96b31c1a7a48b2053c43da1448e8696"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.87/ptyro-0.0.87-x86_64-apple-darwin.tar.gz"
      sha256 "c3a4c43144b810a50be733afb2a85c216ad4b1dcbf0b1a3c497d72702f848abd"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.87/ptyro-0.0.87-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "6da89c84d51b2be32110dfec4a119ceb13423f972bda1b6c23c73d6de1823194"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.87/ptyro-0.0.87-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "90b55d202c2e2845ccc9e7e2a17e71f4a7249ff152cea7aa34c2aa683450608c"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
