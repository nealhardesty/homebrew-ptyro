# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.93/ptyro-0.0.93-aarch64-apple-darwin.tar.gz"
      sha256 "58f05be49b25f88c8d12bb57a52cced276f9ad677cef57d71491d04ed30ff283"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.93/ptyro-0.0.93-x86_64-apple-darwin.tar.gz"
      sha256 "1c1938e7ffa7a54b92913e1b13c3965cd974f92882939593c3a0d2ea0bfa5ab7"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.93/ptyro-0.0.93-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "376b701a5e5589fd90fc58de9033811af8e9bbef55bbc8a5cdb2d5020a3ba0e3"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.93/ptyro-0.0.93-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "5802fbecc96838e28ca5e3e64dddc3d8f2f443d8495f5288d94b845774c7be9c"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
