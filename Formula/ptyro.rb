# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.62/ptyro-0.0.62-aarch64-apple-darwin.tar.gz"
      sha256 "f67a1719cb3232e1c5ab972f048372718717a121dc47dbdd11b2ae3594fe72c4"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.62/ptyro-0.0.62-x86_64-apple-darwin.tar.gz"
      sha256 "f45778009cf1854b493de7b4fea367acaff06a2fe655ea9376befdbd89bb2354"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.62/ptyro-0.0.62-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "f059225fed56cba95631163c34c2de793d03c36da69f4484c5b67936864f7ec7"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.62/ptyro-0.0.62-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "cdc10068311a7ff7a384b3b060e2eac4314e793c3ddd78e7045b163c9eebda2b"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
