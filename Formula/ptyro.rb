# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.12/ptyro-0.0.12-aarch64-apple-darwin.tar.gz"
      sha256 "7ec87819ec372b339f2b2cfe23403802ef2d6b9e9eea73f176e52b517bb06669"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.12/ptyro-0.0.12-x86_64-apple-darwin.tar.gz"
      sha256 "0c2f36c424d34af056e108b419c572b45415f599f1fd0002084bdd86c1206587"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.12/ptyro-0.0.12-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "f1344ffb37a0530323a1e3a698009f6ce5871c1f59e5bd6812543cd632545d2f"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.12/ptyro-0.0.12-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "2944ac839e615dcb84eecebdb3d15e132b9f517dbc4806825f7e34c60ecb1d9c"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
