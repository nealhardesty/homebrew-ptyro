# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.67/ptyro-0.0.67-aarch64-apple-darwin.tar.gz"
      sha256 "3bb39bf8bbed61e7e6cb656f4a650f183cde5c95669976128e0d0e292687509c"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.67/ptyro-0.0.67-x86_64-apple-darwin.tar.gz"
      sha256 "3ab991c31439a3fab883b04a973529ac745a901445a2ee509c5dde75ea253526"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.67/ptyro-0.0.67-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "07368ceffa16ad9335098cc25f33024d8227d87d5737af7c6812f1f96e184896"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.67/ptyro-0.0.67-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "3129a8fdad54550036813ceb27dd7526a5f8f78968be6dae04b9ee5a6a922542"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
