# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.68/ptyro-0.0.68-aarch64-apple-darwin.tar.gz"
      sha256 "490f8aac672a81706f66b1afceef8fd3f9aac6c97fd22b271a66ffe0d7768fe7"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.68/ptyro-0.0.68-x86_64-apple-darwin.tar.gz"
      sha256 "657f67462ea9dc2459367848a55acf8124ef1b9b3c2fde7961d75e64bd59014a"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.68/ptyro-0.0.68-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "0a68544d920ca3a2f6ba04decf6f9ae4ce811b25c7f710094cf3ae3062fac4ed"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.68/ptyro-0.0.68-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "f159ba033f991362c40fe3c315e370012c57c80cbad5dc0bb70fed9b67174120"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
