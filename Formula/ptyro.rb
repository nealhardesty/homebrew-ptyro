# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.64/ptyro-0.0.64-aarch64-apple-darwin.tar.gz"
      sha256 "6d729d606610068e1477aca40f4d1bdddeb64a4ad1400de67ab284f59cd9722e"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.64/ptyro-0.0.64-x86_64-apple-darwin.tar.gz"
      sha256 "1e7378e599d60356a056f35c54894019496830e860488f26a166fd17eec44c4f"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.64/ptyro-0.0.64-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "ea14f20b526da0b8a4d0f7f78a17b725b2d95ba689a4242862e3e40714624cfa"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.64/ptyro-0.0.64-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "5297b3d0f54b1958726208badb2ed19986cacff18ca8437687adc1d3ea8e0163"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
