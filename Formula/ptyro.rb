# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.43/ptyro-0.0.43-aarch64-apple-darwin.tar.gz"
      sha256 "1b7c5d99c07f30173cdae814eed1b1ee63d32af57d677803734b437bd89ff5f0"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.43/ptyro-0.0.43-x86_64-apple-darwin.tar.gz"
      sha256 "8617374ac46a7118041a85e679926204274a2d4d8b612fe4710c7bca4bdb0f5a"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.43/ptyro-0.0.43-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "37a2cbe475472217c94a5b72ff19a0f9ecf736f29a7247c72e496e9cd97d85e0"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.43/ptyro-0.0.43-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "31619adff29951f684bfcca84d43ad3d8cae622dafb3dc4af12e93e7b333d1f1"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
