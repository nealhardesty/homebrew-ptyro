# Homebrew formula for ptyro, rendered by `make homebrew-formula` (scripts/homebrew.sh) from the
# release checksums. The release workflow pushes it to the tap: brew install nealhardesty/ptyro/ptyro
class Ptyro < Formula
  desc "Terminal-native home for your coding agents"
  homepage "https://github.com/nealhardesty/ptyro"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  # ptyro runs git for worktrees and snapshots. macOS ships one (Xcode tools); Linux gets brew's.
  # `gh` is optional (pull requests, `ptyro ship`): the caveats say so.
  uses_from_macos "git"

  on_macos do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.89/ptyro-0.0.89-aarch64-apple-darwin.tar.gz"
      sha256 "9db2d51fcba81c7fac640f76642047fcaf20a135ae3a334bb649000a70a8ceaa"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.89/ptyro-0.0.89-x86_64-apple-darwin.tar.gz"
      sha256 "67b96a17ceafe5ce4041d10ce419069914b1df3b9a400deea9e31d244e17f0e2"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.89/ptyro-0.0.89-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "9d534d90676d1a68c7c1790fdc1c7c09485aa3e5b313cb168ffd396f4166a8e4"
    end
    on_intel do
      url "https://github.com/nealhardesty/ptyro/releases/download/v0.0.89/ptyro-0.0.89-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "2b0db047d4ae7e2aae90540468aaadde6c51d16eef4ad7cc5f7aac9328cf86a1"
    end
  end

  def install
    bin.install "ptyro"
    # Generated by the installed binary, so they always match it (and every tarball, even a
    # cross-built one that shipped without completions, installs the same way).
    generate_completions_from_executable(bin/"ptyro", "completions")
  end

  def caveats
    <<~EOS
      Upgrading? `brew upgrade ptyro` installs the new binary; sessions keep running across it with:
        ptyro daemon upgrade
      `gh` (the GitHub CLI) is optional: install it for pull-request features (brew install gh).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ptyro --version")
  end
end
